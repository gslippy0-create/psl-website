    @app.post("/contract-offers/<int:offer_id>/accept")
    def accept_contract_offer(offer_id):
        user = current_user()
        if not user or not user["player_id"]:
            return login_required()
        c = db()
        try:
            if not os.getenv("DATABASE_URL"):
                c.execute("BEGIN IMMEDIATE")
            offer = c.execute("""SELECT o.*,p.team_id player_team_id,p.name player_name,t.name team_name
                FROM contract_offers o JOIN players p ON p.id=o.player_id JOIN teams t ON t.id=o.team_id
                WHERE o.id=? AND o.player_id=? AND o.status='pending'""",
                (offer_id, user["player_id"])).fetchone()
            if not offer:
                raise ValueError("Offer not found or already answered.")
            if offer["player_team_id"] is not None:
                raise ValueError("Your player is already signed to a club.")
            active = c.execute("SELECT id FROM contracts WHERE player_id=? AND status='active' LIMIT 1",
                                (offer["player_id"],)).fetchone()
            if active:
                raise ValueError("An active contract already exists for this player.")
            # Existing contract table uses transfer_fee. Preserve its schema.
            c.execute("""INSERT INTO contracts(player_id,team_id,start_date,end_date,duration_months,transfer_fee,status)
                VALUES(?,?,?,?,?,?, 'active')""",
                (offer["player_id"], offer["team_id"], offer["start_date"], offer["end_date"],
                 offer["duration_months"], offer["fee"] or 0))
            c.execute("UPDATE players SET team_id=? WHERE id=?", (offer["team_id"], offer["player_id"]))
            c.execute("INSERT INTO transfers(player_id,from_team,to_team) VALUES(?,?,?)",
                       (offer["player_id"], "Free Agent", offer["team_name"]))
            c.execute("UPDATE contract_offers SET status='accepted',responded_at=CURRENT_TIMESTAMP WHERE id=?",
                      (offer_id,))
            c.execute("""UPDATE contract_offers SET status='rejected',responded_at=CURRENT_TIMESTAMP
                WHERE player_id=? AND status='pending' AND id<>?""", (offer["player_id"], offer_id))
            c.commit()
        except Exception as exc:
            c.rollback()
            c.close()
            return render_template("message.html", title="Could not accept offer", message=str(exc)), 400
        c.close()
        return redirect(url_for("career_player", player_id=user["player_id"]))

