    @app.route("/club-management", methods=["GET", "POST"])
    def club_management():
        ensure_tables()
        user, team = manager_team()
        if not admin_user() and not team:
            if not user and not session.get("discord_id"):
                return login_required()
            return "Your account is not linked to a PSL club.", 403
        c = db()
        if request.method == "POST":
            if not admin_user():
                c.close()
                return "Only a PSL administrator can edit club budgets.", 403
            try:
                team_id = int(request.form.get("team_id", "0"))
                budget = float(request.form.get("transfer_budget", "0") or 0)
                wages = float(request.form.get("wage_budget", "0") or 0)
                if budget < 0 or wages < 0:
                    raise ValueError("Budgets cannot be negative.")
                exists = c.execute("SELECT id FROM teams WHERE id=?", (team_id,)).fetchone()
                if not exists:
                    raise ValueError("Club not found.")
                if os.getenv("DATABASE_URL"):
                    c.execute("""INSERT INTO club_finances(team_id,transfer_budget,wage_budget,updated_at)
                        VALUES(?,?,?,CURRENT_TIMESTAMP) ON CONFLICT(team_id) DO UPDATE SET
                        transfer_budget=EXCLUDED.transfer_budget,wage_budget=EXCLUDED.wage_budget,updated_at=CURRENT_TIMESTAMP""",
                        (team_id, budget, wages))
                else:
                    c.execute("""INSERT INTO club_finances(team_id,transfer_budget,wage_budget,updated_at)
                        VALUES(?,?,?,CURRENT_TIMESTAMP) ON CONFLICT(team_id) DO UPDATE SET
                        transfer_budget=excluded.transfer_budget,wage_budget=excluded.wage_budget,updated_at=CURRENT_TIMESTAMP""",
                        (team_id, budget, wages))
                c.commit()
            except Exception:
                c.rollback()
        if admin_user():
            teams = c.execute("""SELECT t.*,COALESCE(f.transfer_budget,0) transfer_budget,
                    COALESCE(f.wage_budget,0) wage_budget FROM teams t LEFT JOIN club_finances f ON f.team_id=t.id
                    ORDER BY t.name""").fetchall()
            selected = team
        else:
            teams = c.execute("""SELECT t.*,COALESCE(f.transfer_budget,0) transfer_budget,
                    COALESCE(f.wage_budget,0) wage_budget FROM teams t LEFT JOIN club_finances f ON f.team_id=t.id
                    WHERE t.id=?""", (team["id"],)).fetchall()
            selected = team
        if selected:
            squad = c.execute("SELECT * FROM players WHERE team_id=? ORDER BY position,name", (selected["id"],)).fetchall()
            fixtures = c.execute("""SELECT f.*,h.name home,a.name away FROM fixtures f
                JOIN teams h ON h.id=f.home_id JOIN teams a ON a.id=f.away_id
                WHERE (f.home_id=? OR f.away_id=?) ORDER BY CASE WHEN f.status='scheduled' THEN 0 ELSE 1 END,
                f.scheduled,f.id LIMIT 12""", (selected["id"], selected["id"])).fetchall()
        else:
            squad, fixtures = [], []
        c.close()
        return render_template("club_management.html", teams=teams, selected=selected, squad=squad,
                               fixtures=fixtures, is_admin=admin_user())

