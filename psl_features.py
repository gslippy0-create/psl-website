    def current_user():
        uid = session.get("user_id")
        if not uid:
            return None
        c = db()
        row = c.execute("SELECT * FROM users WHERE id=?", (uid,)).fetchone()
        c.close()
        return row

    def manager_team():
        user = current_user()
        discord_id = session.get("discord_id")
        c = db()
        team = None
        if user:
            if user["team_id"]:
                team = c.execute("SELECT * FROM teams WHERE id=?", (user["team_id"],)).fetchone()
            if not team and user["username"]:
                team = c.execute("SELECT * FROM teams WHERE lower(trim(manager))=lower(trim(?)) LIMIT 1",
                                 (user["username"],)).fetchone()
        if not team and discord_id:
            team = c.execute("SELECT * FROM teams WHERE discord_id=?", (discord_id,)).fetchone()
        c.close()
        return user, team

    def admin_user():
        return bool(session.get("admin") or session.get("is_admin"))

    def login_required():
        return redirect(url_for("login", next=request.path))

    def add_months(start, months):
        import calendar
        y = start.year + (start.month - 1 + months) // 12
        m = (start.month - 1 + months) % 12 + 1
        return date(y, m, min(start.day, calendar.monthrange(y, m)[1]))

    ensure_tables()

    @app.get("/career")
    def career_index():
        c = db()
        rows = c.execute("""SELECT p.id,p.name,p.position,COALESCE(t.name,'Free Agent') team,
                p.appearances,p.goals,p.assists,
                CASE WHEN p.appearances>0 THEN ROUND(1.0*p.goals/p.appearances,2) ELSE 0 END goals_per_app
            FROM players p LEFT JOIN teams t ON t.id=p.team_id
            ORDER BY p.goals DESC,p.assists DESC,p.appearances DESC,p.name""").fetchall()
        c.close()
        return render_template("career.html", players=rows)

    @app.get("/career/<int:player_id>")
    def career_player(player_id):
        c = db()
        player = c.execute("""SELECT p.*,COALESCE(t.name,'Free Agent') team
            FROM players p LEFT JOIN teams t ON t.id=p.team_id WHERE p.id=?""", (player_id,)).fetchone()
        if not player:
            c.close()
            abort(404)
        matches = c.execute("""SELECT s.*,f.scheduled,f.round_no,h.name home,a.name away,
                f.home_score,f.away_score,f.status
            FROM player_match_stats s LEFT JOIN fixtures f ON f.id=s.fixture_id
            LEFT JOIN teams h ON h.id=f.home_id LEFT JOIN teams a ON a.id=f.away_id
            WHERE s.player_id=? ORDER BY s.id DESC LIMIT 50""", (player_id,)).fetchall()
        transfers = c.execute("SELECT * FROM transfers WHERE player_id=? ORDER BY id DESC", (player_id,)).fetchall()
        contracts = c.execute("""SELECT co.*,t.name team FROM contracts co JOIN teams t ON t.id=co.team_id
            WHERE co.player_id=? ORDER BY co.id DESC""", (player_id,)).fetchall()
        season = c.execute("""SELECT COALESCE(SUM(appearances),0) apps,COALESCE(SUM(goals),0) goals,
                COALESCE(SUM(assists),0) assists,ROUND(AVG(rating),2) avg_rating
            FROM player_match_stats WHERE player_id=?""", (player_id,)).fetchone()
        c.close()
        return render_template("career_player.html", player=player, matches=matches,
                               transfers=transfers, contracts=contracts, season=season)

    @app.route("/transfer-market", methods=["GET", "POST"])
    def transfer_market():
        ensure_tables()
        user, team = manager_team()
        message = request.args.get("message", "")
        error = ""
        if request.method == "POST":
            if not user and not session.get("discord_id"):
                return login_required()
            if not team:
                return "Your account is not linked to a PSL club. Ask an admin to link your account to a team.", 403
            try:
                player_id = int(request.form.get("player_id", "0"))
                months = int(request.form.get("duration_months", "3"))
                fee = float(request.form.get("fee", "0") or 0)
                start_text = request.form.get("start_date") or date.today().isoformat()
                start = date.fromisoformat(start_text)
                if months not in (1, 3, 6, 12):
                    raise ValueError("Choose a contract length of 1, 3, 6 or 12 months.")
                if fee < 0:
                    raise ValueError("Fee cannot be negative.")
                c = db()
                player = c.execute("SELECT * FROM players WHERE id=? AND team_id IS NULL", (player_id,)).fetchone()
                if not player:
                    c.close()
                    raise ValueError("That player is no longer available as a free agent.")
                if os.getenv("DATABASE_URL"):
                    c.execute("""INSERT INTO contract_offers
                        (player_id,team_id,start_date,end_date,duration_months,fee,status,offered_by_user_id)
                        VALUES(?,?,?,?,?,?,'pending',?)""",
                        (player_id, team["id"], start.isoformat(), add_months(start, months).isoformat(),
                         months, fee, user["id"] if user else None))
                else:
                    c.execute("""INSERT INTO contract_offers
                        (player_id,team_id,start_date,end_date,duration_months,fee,status,offered_by_user_id)
                        VALUES(?,?,?,?,?,?,'pending',?)""",
                        (player_id, team["id"], start.isoformat(), add_months(start, months).isoformat(),
                         months, fee, user["id"] if user else None))
                c.commit()
                c.close()
                return redirect(url_for("transfer_market", message=f"Contract offer sent for {player['name']}."))
            except Exception as exc:
                error = str(exc)
        c = db()
        free_agents = c.execute("""SELECT p.*,COALESCE(t.name,'Free Agent') team FROM players p
            LEFT JOIN teams t ON t.id=p.team_id WHERE p.team_id IS NULL ORDER BY p.position,p.name""").fetchall()
        latest = c.execute("""SELECT tr.*,p.name player FROM transfers tr JOIN players p ON p.id=tr.player_id
            ORDER BY tr.id DESC LIMIT 12""").fetchall()
        offers = []
        if team:
            offers = c.execute("""SELECT o.*,p.name player FROM contract_offers o JOIN players p ON p.id=o.player_id
                WHERE o.team_id=? ORDER BY o.id DESC LIMIT 10""", (team["id"],)).fetchall()
        c.close()
        return render_template("transfer_market.html", team=team, free_agents=free_agents,
                               latest=latest, offers=offers, message=message, error=error, today=date.today().isoformat())

